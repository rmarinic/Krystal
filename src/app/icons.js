/* An inline SVG for markup built in JS. Unknown names give '' (never a broken
 * glyph). `cls` adds classes next to the shared `ui-ico`. */
function icon(name, cls) {
  const paths = ICON_PATHS[name];
  if (!paths) return '';
  return `<svg class="ui-ico${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" aria-hidden="true">${paths}</svg>`;
}

/* For call sites that take "an icon" loosely (a tip's, a progress overlay's):
 * a known name becomes the icon; anything else is shown as the text it is. */
function iconOrText(nameOrText) {
  return ICON_PATHS[nameOrText] ? icon(nameOrText) : escapeHtml(String(nameOrText || ''));
}

/* The data-icon="…" masks: one rule per icon, built from the same paths. */
(function installIconMasks() {
  const svgOpen = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" ' +
    'stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">';
  const rules = Object.keys(ICON_PATHS).map((n) =>
    `[data-icon="${n}"]{--icon:url("data:image/svg+xml,${encodeURIComponent(svgOpen + ICON_PATHS[n] + '</svg>')}")}`);
  const style = document.createElement('style');
  style.id = 'icon-masks';
  style.textContent = rules.join('\n');
  document.head.appendChild(style);
})();
